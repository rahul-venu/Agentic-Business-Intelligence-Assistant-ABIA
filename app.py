# 7. DYNAMIC PLOTLY CHART ENGINE
# -------------------------------------------------------------
def render_dynamic_plotly_chart(df: pd.DataFrame, plan):
    if df is None or df.empty or len(df.columns) < 2:
        return

    chart_type = getattr(plan, "chart_type", "bar") if plan else "bar"
    if chart_type == "table_only":
        return

    numeric_cols = df.select_dtypes(include=["number"]).columns.tolist()
    text_time_cols = df.select_dtypes(
        include=["object", "category", "datetime"]
    ).columns.tolist()

    if not numeric_cols:
        return

    st.markdown("### 📈 Visual Analytics")

    # 1. PIE / DONUT CHART
    if chart_type == "pie" and text_time_cols and numeric_cols:
        fig = px.pie(
            df,
            names=text_time_cols[0],
            values=numeric_cols[0],
            hole=0.4,
            title=f"Distribution Share: {numeric_cols[0].replace('_', ' ').title()} by {text_time_cols[0].title()}",
        )
        st.plotly_chart(fig, use_container_width=True)

    # 2. LINE / TREND CHART (Multi-series support with Auto-Aggregation)
    elif chart_type == "line" and text_time_cols and numeric_cols:
        time_col = text_time_cols[0]
        # Identify time-based column
        for col in text_time_cols:
            if any(
                t in col.lower() for t in ["month", "year", "date", "day", "quarter"]
            ):
                time_col = col
                break

        metric = numeric_cols[0]

        if len(text_time_cols) >= 2:
            group_col = next(c for c in text_time_cols if c != time_col)

            # Collapse raw order rows into 1 sum per month per region
            plot_df = df.groupby([time_col, group_col])[metric].sum().reset_index()
            # Sort by time to ensure smooth line rendering
            plot_df = plot_df.sort_values(by=time_col)

            fig = px.line(
                plot_df,
                x=time_col,
                y=metric,
                color=group_col,
                markers=True,
                title=f"Trend Comparison: {metric.replace('_', ' ').title()} by {group_col.title()} over {time_col.title()}",
            )
        else:
            plot_df = (
                df.groupby(time_col)[metric]
                .sum()
                .reset_index()
                .sort_values(by=time_col)
            )
            fig = px.line(
                plot_df,
                x=time_col,
                y=metric,
                markers=True,
                title=f"Trend Analysis: {metric.replace('_', ' ').title()} over {time_col.title()}",
            )
        st.plotly_chart(fig, use_container_width=True)

    # 3. AREA CHART
    elif chart_type == "area" and text_time_cols and numeric_cols:
        time_col = text_time_cols[0]
        fig = px.area(
            df,
            x=time_col,
            y=numeric_cols[0],
            color=text_time_cols[1] if len(text_time_cols) >= 2 else None,
            title=f"Volume Growth: {numeric_cols[0].replace('_', ' ').title()} over {time_col.title()}",
        )
        st.plotly_chart(fig, use_container_width=True)

    # 4. SCATTER PLOT
    elif chart_type == "scatter" and len(numeric_cols) >= 2:
        fig = px.scatter(
            df,
            x=numeric_cols[0],
            y=numeric_cols[1],
            color=text_time_cols[0] if text_time_cols else None,
            size=numeric_cols[0],
            hover_data=df.columns,
            title=f"Correlation: {numeric_cols[0].replace('_', ' ').title()} vs {numeric_cols[1].replace('_', ' ').title()}",
        )
        st.plotly_chart(fig, use_container_width=True)

    # 5. BAR CHART (Default)
    elif text_time_cols and numeric_cols:
        if len(text_time_cols) >= 2:
            fig = px.bar(
                df,
                x=text_time_cols[0],
                y=numeric_cols[0],
                color=text_time_cols[1],
                barmode="group",
                title=f"{numeric_cols[0].replace('_', ' ').title()} Breakdown by {text_time_cols[0].title()} & {text_time_cols[1].title()}",
            )
        else:
            fig = px.bar(
                df,
                x=text_time_cols[0],
                y=numeric_cols[0],
                color=text_time_cols[0],
                title=f"{numeric_cols[0].replace('_', ' ').title()} by {text_time_cols[0].title()}",
            )
        st.plotly_chart(fig, use_container_width=True)


