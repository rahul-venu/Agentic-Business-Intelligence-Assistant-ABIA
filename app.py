# 6. EXECUTIVE KPI METRIC CARDS RENDERER (DYNAMIC)
# Renders 4 high-level summary cards at the top of responses
# -------------------------------------------------------------
def render_kpi_cards(df: pd.DataFrame):
    """Dynamically parses ANY returned columns and renders adaptive KPI cards."""
    if df is None or df.empty:
        return

    numeric_cols = df.select_dtypes(include=["number"]).columns.tolist()
    text_cols = df.select_dtypes(
        include=["object", "category", "datetime"]
    ).columns.tolist()

    if not numeric_cols:
        return

    st.markdown("### 📌 Executive Summary KPIs")
    # Dynamically create 2 to 4 KPI card columns
    num_cards = min(len(numeric_cols) + (1 if text_cols else 0), 4)
    cols = st.columns(num_cards)

    col_idx = 0

    # Card 1: Primary Metric
    m1 = numeric_cols[0]
    m1_name = m1.replace("_", " ").title()
    if any(k in m1.lower() for k in ["rate", "margin", "pct"]):
        cols[col_idx].metric(label=f"📊 Avg {m1_name}", value=f"{df[m1].mean():.1f}%")
    elif any(k in m1.lower() for k in ["price", "revenue", "cost", "profit"]):
        cols[col_idx].metric(label=f"💵 Total {m1_name}", value=f"${df[m1].sum():,.2f}")
    else:
        cols[col_idx].metric(label=f"📦 Total {m1_name}", value=f"{df[m1].sum():,.0f}")
    col_idx += 1

    # Card 2: Secondary Metric (if present)
    if len(numeric_cols) > 1 and col_idx < num_cards:
        m2 = numeric_cols[1]
        m2_name = m2.replace("_", " ").title()
        if any(k in m2.lower() for k in ["rate", "margin", "pct"]):
            cols[col_idx].metric(
                label=f"📈 Avg {m2_name}", value=f"{df[m2].mean():.1f}%"
            )
        elif any(k in m2.lower() for k in ["price", "revenue", "cost", "profit"]):
            cols[col_idx].metric(
                label=f"💰 Total {m2_name}", value=f"${df[m2].sum():,.2f}"
            )
        else:
            cols[col_idx].metric(
                label=f"📦 Total {m2_name}", value=f"{df[m2].sum():,.0f}"
            )
        col_idx += 1

    # Card 3: Third Metric or Average (if present)
    if len(numeric_cols) > 2 and col_idx < num_cards:
        m3 = numeric_cols[2]
        m3_name = m3.replace("_", " ").title()
        cols[col_idx].metric(label=f"📊 Avg {m3_name}", value=f"${df[m3].mean():,.2f}")
        col_idx += 1

    # Card 4: Categorical Group Count / Entity Scope
    if text_cols and col_idx < num_cards:
        entity_name = text_cols[0].replace("_", " ").title()
        cols[col_idx].metric(label=f"🏷️ {entity_name} Analyzed", value=f"{len(df):,}")

    st.divider()


